"""Настройки сервиса диаризации и опознания говорящего.

Всё через окружение, потому что порог опознания придётся менять по мере того,
как накопятся образцы реальных голосов, а трогать код ради числа — плохая
привычка: так теряется связь числа с замером, которым оно получено.
"""
from __future__ import annotations

import os

# Каталог данных. Один параметр окружения, потому что в контейнере это том,
# а при запуске из исходников — каталог рядом с кодом.
ROOT = os.environ.get("DIAR_DATA_DIR", os.path.join(os.path.dirname(os.path.abspath(__file__)), "data"))

HOST = os.environ.get("DIAR_HOST", "0.0.0.0")
PORT = int(os.environ.get("DIAR_PORT", "18010"))
DEVICE = os.environ.get("DIAR_DEVICE", "cuda:0")

# Sortformer, а не pyannote. Замерено на 48 отрезках с разметкой слушателя:
# 85.5 % сбалансированной точности против 74.2 % у разреза по ECAPA, и при той
# же полноте вчетверо меньше лишних разрезов. На приёмке 158 отрезков — НОЛЬ
# дефектов против 7 из 48 у pyannote (точный тест p = 2.6e-05). Им же размечен
# многотысячный архив телефонных записей.
DIAR_MODEL = os.environ.get("DIAR_MODEL", "nvidia/diar_streaming_sortformer_4spk-v2")
FRAME = 0.08                      # шаг апостериорных вероятностей Sortformer, с
MAX_SPEAKERS = 4                  # столько их у этой модели, больше не бывает

# TitaNet-L из того же NeMo, а НЕ speechbrain-ECAPA, которым считались
# `mine_speakers.py` и `diar_resplit.py`. Причина не в качестве: speechbrain
# тянет torchaudio, которого в этой среде нет, а порог из тех работ сюда всё
# равно не переносится — там решалась ДРУГАЯ задача (есть ли смена говорящего
# между соседними окнами), и калиброванный на ней 0.53 к опознанию по образцу
# отношения не имеет. Переносить его было бы ровно той ошибкой, которую этот
# проект уже записал трижды: порог, вынесенный за материал, на котором снят.
SPK_MODEL = os.environ.get("DIAR_SPK_MODEL", "titanet_large")
SPK_DIM = 192

SR = 16000
MIN_SEG_S = float(os.environ.get("DIAR_MIN_SEG_S", "0.5"))
MAX_SEG_S = float(os.environ.get("DIAR_MAX_SEG_S", "60"))
MAX_UPLOAD_MB = int(os.environ.get("DIAR_MAX_UPLOAD_MB", "200"))

# Сколько секунд речи одного говорящего склеивать перед вычислением эмбеддинга.
# TitaNet на коротком отрезке возвращает шум — тот же эффект, что записан про
# ECAPA в `diar_resplit.py`. Ниже MIN_EMBED_S опознание не выдаётся вовсе.
EMBED_POOL_S = float(os.environ.get("DIAR_EMBED_POOL_S", "20"))
MIN_EMBED_S = float(os.environ.get("DIAR_MIN_EMBED_S", "2.0"))

# Порог опознания. ЗАМЕРЕН, а не выбран, и первое значение (0.60) было НЕВЕРНО.
#
# Решающий замер — пары «два говорящих ИЗ ОДНОЙ ЗАПИСИ»: их разделил
# Sortformer, значит это заведомо разные люди, и метка не стоит ничего и не
# может быть неправильной. Несколько сотен таких пар, ложное принятие:
#
#     порог 0.60 -> 3.44 %      0.75 -> 1.72 %      0.85 -> 0.69 %
#
# Два замера, которые к этому вели, и оба сначала обманули:
#   * калибровка «между записями» дала НУЛЕВОЕ разделение (0.468 против 0.466).
#     Виновата метка: внутренний номер это РАБОЧЕЕ МЕСТО, а не человек — за
#     день на нём сменяется несколько операторов; плюс сама статистика брала
#     максимум из четырёх пар и тем задирала обе стороны.
#   * кластеризация при 0.60 слепила 530 голосов из 584 в один кластер.
#     Это ЦЕПОЧКА одиночной связи (A~B, B~C склеивают A с C), а не отказ модели:
#     перебор порогов показывает, что гигант рассыпается на 0.70, а с 0.75 по
#     0.85 держится плато из 21-22 кластеров — подпись реальной структуры.
# Что модель это УМЕЕТ, показано отдельно на настоящих метках: KazakhTTS2, пять
# дикторов — 100 % своих при 0 % чужих, и телефонная полоса стоит почти ничего
# (0.804 -> 0.780).
#
# ЧТО ЕЩЁ НЕ ИЗМЕРЕНО: ПОЛНОТА на кросс-записи. Пар «один человек в двух
# разных записях» с надёжной меткой нет, а без них «сколько своих мы
# отвергаем» — оценка, а не число. Порог перемеряется на СВОЁМ материале.
MATCH_THRESHOLD = float(os.environ.get("DIAR_MATCH_THRESHOLD", "0.78"))

REGISTRY = os.environ.get("DIAR_REGISTRY", f"{ROOT}/speakers/registry.json")
TMPDIR = "/dev/shm" if os.path.isdir("/dev/shm") else "/tmp"
